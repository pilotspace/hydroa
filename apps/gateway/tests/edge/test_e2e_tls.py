"""Red suite — e2e TLS termination tests (contract §3, edge-tls TASK.md).

Layer: @pytest.mark.e2e — requires the infra/docker-compose.e2e.yml stack to be running
with TLS certs generated by scripts/gen_dev_certs.sh.
Excluded from the default pytest run via pyproject.toml addopts: -m "not e2e".

Run by scripts/e2e_edge.sh (extended for TLS) or manually:
  uv run pytest tests/edge/test_e2e_tls.py -m e2e -q --no-cov

These tests are RED-BY-ABSENCE when the stack lacks TLS:
  - The :8443 port is not bound   -> httpx.ConnectError
  - No TLS certs exist            -> FileNotFoundError on CA cert load
  - envoy.yaml has no TLS listener-> httpx.ConnectError or SSL handshake failure

All TLS tests hit https://localhost:8443 (Envoy TLS listener) — NOT the gateway directly.
Existing :8080 tests in test_e2e_edge.py are NOT modified or duplicated here.

Configuration via environment variables:
  E2E_BASE_URL    — HTTP base URL (default: http://localhost:8080)
  E2E_TLS_URL     — HTTPS base URL (default: https://localhost:8443)
  E2E_CA_CERT     — path to dev CA cert for TLS verification
                    (default: infra/envoy/certs/dev-ca.pem, relative to repo root)
  GATEWAY_JWT_SECRET — shared JWT secret (default: e2e-test-secret-change-me)
  E2E_PROD_STACK  — set to "1" to enable S8 production-redirect test (requires
                    docker-compose.prod.yml stack running separately on 8080/8443)

IMPORTANT: Do NOT mark individual tests with skip — they must FAIL (not skip) when the
stack is not present. The e2e script is responsible for ensuring the stack is up before
running these tests. The sole exception is test_http_redirects_to_https_prod_topology
which requires a separate prod stack and is explicitly conditional-skip guarded.
"""

