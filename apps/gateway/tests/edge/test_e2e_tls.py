def _tls_client(ca_cert: str = E2E_CA_CERT) -> httpx.AsyncClient:
    """Return an AsyncClient that verifies TLS against the dev CA cert.

    RED reason: if E2E_CA_CERT does not exist (certs not generated),
    httpx raises ssl.SSLError or FileNotFoundError on first use.
    """
    ssl_ctx = ssl.create_default_context(cafile=ca_cert)
    return httpx.AsyncClient(verify=ssl_ctx)


async def _https_signup_and_login(
    client: httpx.AsyncClient,
    *,
    tenant_name: str,
    email: str,
) -> str:
    """Sign up a fresh tenant over HTTPS :8443 and return a valid JWT."""
    password = "e2e-tls-correct-horse-battery"
    sr = await client.post(
        f"{E2E_TLS_URL}{SIGNUP_PATH}",
        json={"tenant_name": tenant_name, "email": email, "password": password},
        timeout=10.0,
    )
    assert sr.status_code == 201, (
        f"HTTPS signup failed (status {sr.status_code}): {sr.text}\n"
        "Check: is the TLS stack up? Did gen_dev_certs.sh run? Is :8443 exposed?"
    )
    lr = await client.post(
        f"{E2E_TLS_URL}{LOGIN_PATH}",
        json={"email": email, "password": password},
        timeout=10.0,
    )
    assert lr.status_code == 200, f"HTTPS login failed: {lr.text}"
    return lr.json()["access_token"]


async def _https_create_key(
    client: httpx.AsyncClient,
    jwt_token: str,
    name: str,
) -> dict[str, Any]:
    resp = await client.post(
        f"{E2E_TLS_URL}{ADMIN_KEYS_PATH}",
        json={"name": name},
        headers={"Authorization": f"Bearer {jwt_token}"},
        timeout=10.0,
    )
    assert resp.status_code == 201, (
        f"HTTPS key creation failed (status {resp.status_code}): {resp.text}"
    )
    return resp.json()


