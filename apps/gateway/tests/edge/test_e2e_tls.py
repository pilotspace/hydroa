async def test_tls_handshake_health() -> None:
    """S1: TLS handshake with dev CA succeeds; /health returns 200.

    RED reason: :8443 is not bound (Envoy has no TLS listener) or
    E2E_CA_CERT does not exist (certs not generated by gen_dev_certs.sh).
    The failure mode is httpx.ConnectError or ssl.SSLError — not a wrong status code.
    """
    async with _tls_client() as client:
        resp = await client.get(f"{E2E_TLS_URL}{HEALTH_PATH}", timeout=5.0)

    assert resp.status_code == 200, (
        f"Expected 200 from gateway /health over HTTPS :8443, got {resp.status_code}: {resp.text}\n"
        "If you see a connection error above, the TLS listener is not configured.\n"
        "Run scripts/gen_dev_certs.sh and ensure :8443 is exposed in the e2e compose."
    )


# ---------------------------------------------------------------------------
# S2 — plain HTTP to :8443 is rejected at transport layer
# ---------------------------------------------------------------------------


async def test_plain_http_to_tls_port_rejected() -> None:
    """S2: A plain HTTP (non-TLS) request to :8443 must fail at transport layer.

    Envoy's TLS listener expects a TLS ClientHello; sending a plain HTTP request
    causes a TLS alert or TCP reset — httpx raises RemoteProtocolError or ConnectError.
    RED reason: if :8443 is not bound at all, we also get ConnectError (correct red).
    """
    with pytest.raises((httpx.RemoteProtocolError, httpx.ConnectError)):
        async with httpx.AsyncClient(verify=False) as client:  # noqa: S501
            # verify=False allows us to reach the port; but no TLS ClientHello is sent
            # because we use http:// scheme — httpx sends plain HTTP to a TLS port
            await client.get(
                f"http://localhost:8443{HEALTH_PATH}",
                timeout=5.0,
            )


