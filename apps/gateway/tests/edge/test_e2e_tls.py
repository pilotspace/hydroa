E2E_BASE_URL: str = os.environ.get("E2E_BASE_URL", "http://localhost:8080")
E2E_TLS_URL: str = os.environ.get("E2E_TLS_URL", "https://localhost:8443")

_DEFAULT_CA_CERT = str(_REPO_ROOT / "infra" / "envoy" / "certs" / "dev-ca.pem")
E2E_CA_CERT: str = os.environ.get("E2E_CA_CERT", _DEFAULT_CA_CERT)

E2E_JWT_SECRET: str = os.environ.get("GATEWAY_JWT_SECRET", "e2e-test-secret-change-me")

