# S6 — existing HTTP :8080 listener still works (no regression)
# ---------------------------------------------------------------------------


async def test_http_8080_still_works_no_regression() -> None:
    """S6: The HTTP :8080 listener must remain functional alongside :8443.

    This is a guard test: TLS additions must not break the existing e2e stack.
    The full existing e2e suite (test_e2e_edge.py) is the definitive regression check;
    this test confirms at minimum that :8080 is up and the gateway responds.
    RED reason: if TLS changes accidentally disable :8080, this fails immediately.
    """
    async with httpx.AsyncClient() as client:
        resp = await client.get(f"{E2E_BASE_URL}{HEALTH_PATH}", timeout=5.0)

    assert resp.status_code == 200, (
        f"HTTP :8080 /health returned {resp.status_code} after TLS additions — regression detected.\n"
        f"Body: {resp.text}"
    )
    # Confirm no TLS-related headers leaked onto the HTTP listener (HSTS should NOT be
    # present on :8080 — it is a TLS-only header and its presence on HTTP is misleading)
    hsts = resp.headers.get("strict-transport-security", "")
    assert not hsts, (
        f"Strict-Transport-Security unexpectedly present on HTTP :8080 response: {hsts!r}\n"
        "HSTS should only be served on the :8443 TLS listener."
    )


