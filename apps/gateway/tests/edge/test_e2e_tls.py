# ---------------------------------------------------------------------------
# S8 — :8080 redirects to HTTPS in production compose topology
# (conditional: requires E2E_PROD_STACK=1 and docker-compose.prod.yml running)
# ---------------------------------------------------------------------------


async def test_http_redirects_to_https_prod_topology() -> None:
    """S8: In production topology, HTTP :8080 issues a 301 redirect to HTTPS :8443.

    This test requires infra/docker-compose.prod.yml to be running separately.
    It is skipped unless E2E_PROD_STACK=1 is set in the environment.

    RED reason (when E2E_PROD_STACK=1): docker-compose.prod.yml does not exist yet
    (BUILD deliverable), so :8080 either returns 200 or is not bound.
    """
    if os.environ.get("E2E_PROD_STACK", "0") != "1":
        pytest.skip(
            "Production stack test skipped — set E2E_PROD_STACK=1 and start "
            "infra/docker-compose.prod.yml to run this test."
        )

    async with httpx.AsyncClient(follow_redirects=False) as client:
        resp = await client.get(
            f"http://localhost:8080{HEALTH_PATH}",
            timeout=5.0,
        )

    assert resp.status_code in (301, 302), (
        f"Expected redirect (301/302) from HTTP :8080 in production topology, "
        f"got {resp.status_code}: {resp.text!r}"
    )

    location = resp.headers.get("location", "")
    assert "https" in location.lower(), (
        f"Redirect Location header does not point to HTTPS: {location!r}"
    )
    assert "8443" in location or ":443" in location or (
        location.startswith("https://") and ":" not in location.split("//", 1)[1].split("/")[0]
    ), (
        f"Redirect Location does not include :8443 (or standard 443): {location!r}"
    )
