# S3 — full HTTPS flow: signup → login → create key → /v1/ chat
# ---------------------------------------------------------------------------


async def test_https_full_flow_signup_key_v1() -> None:
    """S3: Full signup→login→key→/v1/ flow works identically over HTTPS :8443.

    We do NOT assert a 200 from /v1/ (gateway will fail upstream call without
    a real OpenRouter key). We assert Envoy did not reject the request (not 401/403
    from Envoy ext_authz — same assertion as S8 in test_e2e_edge.py).
    RED reason: :8443 TLS listener not configured; all requests fail at transport.
    """
    async with _tls_client() as client:
        jwt_token = await _https_signup_and_login(
            client,
            tenant_name=f"TLSFlowCo-{uuid.uuid4().hex[:6]}",
            email=f"tls-flow-{uuid.uuid4().hex[:6]}@e2e.io",
        )
        key_body = await _https_create_key(client, jwt_token, "tls-e2e-key")
        full_key: str = key_body["key"]

        resp = await client.post(
            f"{E2E_TLS_URL}{V1_PATH}",
            json={
                "model": "openai/gpt-3.5-turbo",
                "messages": [{"role": "user", "content": "ping"}],
            },
            headers={"Authorization": f"Bearer {full_key}"},
            timeout=10.0,
        )

    # ext_authz passed the request to the gateway when status is NOT 401/403 from Envoy
    assert resp.status_code not in (401, 403), (
        f"Envoy rejected the /v1/ request before reaching the gateway over HTTPS. "
        f"Status: {resp.status_code}, body: {resp.text[:500]!r}."
    )

    # Also confirm :8080 is still reachable (no regression on the HTTP listener)
    async with httpx.AsyncClient() as http_client:
        health = await http_client.get(f"{E2E_BASE_URL}{HEALTH_PATH}", timeout=5.0)
    assert health.status_code == 200, (
        f"HTTP :8080 /health regressed after TLS addition, got {health.status_code}"
    )


# ---------------------------------------------------------------------------
# S4a — HSTS header present on 200 responses from :8443
# ---------------------------------------------------------------------------


async def test_hsts_header_present_on_200() -> None:
    """S4a: Strict-Transport-Security header must be present on :8443 200 responses.

    RED reason: Envoy :8443 listener has no response_headers_to_add for HSTS,
    or :8443 is not bound at all.
    """
    async with _tls_client() as client:
        resp = await client.get(f"{E2E_TLS_URL}{HEALTH_PATH}", timeout=5.0)

    assert resp.status_code == 200, (
        f"Pre-condition failed: expected 200 from /health, got {resp.status_code}"
    )

    hsts = resp.headers.get("strict-transport-security", "")
    assert hsts, (
        f"Strict-Transport-Security header missing on HTTPS /health response.\n"
        f"All response headers: {dict(resp.headers)}"
    )

    # Extract max-age value and assert >= 2 years (63072000 seconds)
    max_age_part = next(
        (p.strip() for p in hsts.split(";") if p.strip().lower().startswith("max-age")),
        None,
    )
    assert max_age_part is not None, (
        f"Strict-Transport-Security header present but has no max-age directive: {hsts!r}"
    )
    max_age_value = int(max_age_part.split("=", 1)[1].strip())
    assert max_age_value >= 63072000, (
        f"HSTS max-age={max_age_value} is less than the required 63072000 (2 years): {hsts!r}"
    )


