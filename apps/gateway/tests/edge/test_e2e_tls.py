# ---------------------------------------------------------------------------
# S5 — TLS version < 1.2 rejected at transport layer
# ---------------------------------------------------------------------------


async def test_tls_version_below_1_2_rejected() -> None:
    """S5: Attempting a TLS 1.1 (or 1.0) handshake to :8443 must be rejected.

    Envoy's tls_minimum_protocol_version: TLSv1_2 causes a handshake_failure alert
    for any client offering only TLS <= 1.1.
    RED reason: :8443 not bound, OR TLS minimum version not configured (allows 1.1).

    Note: Python's ssl module on modern systems may refuse to create a TLS 1.1 context
    at the OS level. We use PROTOCOL_TLS_CLIENT with OP_NO_TLSv1_2 + OP_NO_TLSv1_3
    to force the negotiation attempt. If the OS itself blocks it, the test is skipped
    with an informative message rather than failing (the security property is enforced
    at OS level, which is acceptable).
    """
    try:
        ctx = ssl.SSLContext(ssl.PROTOCOL_TLS_CLIENT)
        ctx.check_hostname = False
        ctx.verify_mode = ssl.CERT_NONE
        # Force only TLS 1.0 / 1.1 by disabling 1.2 and 1.3
        ctx.options |= ssl.OP_NO_TLSv1_2
        ctx.options |= ssl.OP_NO_TLSv1_3
    except AttributeError:
        pytest.skip(
            "ssl.OP_NO_TLSv1_2 / OP_NO_TLSv1_3 not available on this platform — "
            "OS-level TLS 1.1 rejection is in effect; test skipped."
        )

    rejected = False
    try:
        with socket.create_connection(("localhost", 8443), timeout=5.0) as sock:
            with ctx.wrap_socket(sock, server_hostname="localhost"):
                pass  # handshake succeeded — this is the failure case
    except ssl.SSLError:
        rejected = True
    except OSError:
        # Port not bound — counts as a red failure for the right reason
        rejected = False

    assert rejected, (
        "TLS 1.1 handshake to :8443 succeeded — Envoy is NOT enforcing TLSv1_2 minimum. "
        "Set tls_minimum_protocol_version: TLSv1_2 in the DownstreamTlsContext."
    )


