class TestFilesBodyCapBoundary:
    async def test_upload_above_outer_json_cap_below_file_cap_succeeds(
        self, capped_client: httpx.AsyncClient
    ) -> None:
        """A file larger than the outer /v1/ JSON cap but smaller than files_max_bytes is
        accepted — /v1/files has its own (larger) body cap, it does not inherit /v1/'s."""
        keys = await _signup_and_key(
            capped_client,
            tenant_name="FilesCapA",
            email="files-cap-a@example.io",
            password="files-cap-a-battery",
        )
        # 2 KiB: > _OUTER_JSON_CAP (1 KiB) yet < _FILE_CAP (8 KiB). Before the fix the outer
        # /v1/ cap rejects this 413 ERR_REQUEST_BODY_TOO_LARGE.
        payload = b"x" * (2 * 1024)
        resp = await _upload(
            capped_client,
            keys["key"],
            filename="mid.bin",
            data=payload,
            purpose="user_data",
            content_type="application/octet-stream",
        )
        assert resp.status_code == 200, resp.text
        body = resp.json()
        assert body["bytes"] == len(payload)
        assert body["id"].startswith("file-")

    async def test_upload_above_file_cap_is_contracted_413(
        self, capped_client: httpx.AsyncClient
    ) -> None:
        """A file above files_max_bytes returns the CONTRACTED 413 ERR_FILE_TOO_LARGE from
        the router — not the outer guard's ERR_REQUEST_BODY_TOO_LARGE — because the outer
        /v1/files cap carries a headroom above files_max_bytes so the router owns the edge."""
        keys = await _signup_and_key(
            capped_client,
            tenant_name="FilesCapB",
            email="files-cap-b@example.io",
            password="files-cap-b-battery",
        )
        # 9 KiB: > _FILE_CAP (8 KiB) but well under the outer /v1/files cap (8 KiB + 1 MiB
        # headroom), so it reaches the router, which emits the contracted code.
        payload = b"y" * (9 * 1024)
        resp = await _upload(
            capped_client,
            keys["key"],
            filename="big.bin",
            data=payload,
            purpose="user_data",
            content_type="application/octet-stream",
        )
        assert resp.status_code == 413, resp.text
        assert resp.json()["code"] == "ERR_FILE_TOO_LARGE"

    async def test_upload_at_file_cap_boundary_succeeds(
        self, capped_client: httpx.AsyncClient
    ) -> None:
        """Exactly files_max_bytes of raw file bytes is accepted (the reject is strictly
        greater-than) — the multipart framing overhead must NOT push a boundary file over
        the outer guard, which is what the headroom guarantees."""
        keys = await _signup_and_key(
            capped_client,
            tenant_name="FilesCapC",
            email="files-cap-c@example.io",
            password="files-cap-c-battery",
        )
        payload = b"z" * _FILE_CAP  # exactly the cap
        resp = await _upload(
            capped_client,
            keys["key"],
            filename="edge.bin",
            data=payload,
            purpose="user_data",
            content_type="application/octet-stream",
        )
        assert resp.status_code == 200, resp.text
        assert resp.json()["bytes"] == _FILE_CAP
