"""Regression: the /v1/files body-size cap boundary (files-uploads-api PLAN.md §3).

Earned-green refute (2026-07-24): the OUTER BodySizeLimitMiddleware maps "/v1/" ->
max_json_body_bytes (20 MiB) as its longest-prefix default, so before the fix /v1/files
inherited that 20 MiB cap even though files_max_bytes is 512 MiB. Every upload in the
20 MiB -> files_max_bytes range was therefore rejected 413 ERR_REQUEST_BODY_TOO_LARGE and
the CONTRACTED 413 ERR_FILE_TOO_LARGE (§3 Reject) could never fire for that whole range —
and the frozen suite only ever probed tiny fixtures, so it never caught it.

These tests pin the boundary with a SECOND app built with tiny caps (outer JSON cap 1 KiB,
per-file cap 8 KiB) so the realistic "above the outer /v1/ cap, below files_max_bytes"
window is exercised with KiB-sized generated bytes (no giant literals, fast):

  - a file ABOVE the outer /v1/ JSON cap but BELOW files_max_bytes -> 200 (the dedicated
    /v1/files route cap overrides the wider /v1/ cap). WITHOUT the fix this is a 413
    ERR_REQUEST_BODY_TOO_LARGE.
  - a file ABOVE files_max_bytes -> the contracted 413 ERR_FILE_TOO_LARGE, emitted by the
    ROUTER (not the outer guard) — proving the router owns the exact boundary because the
    outer cap carries a headroom above files_max_bytes.
"""

