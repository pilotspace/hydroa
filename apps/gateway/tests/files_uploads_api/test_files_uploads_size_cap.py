# Local copies of the frozen suite's helpers (kept local rather than imported so the frozen
# test module is never touched and no private symbol is imported across modules).
def _bearer(key: str) -> dict[str, str]:
    return {"Authorization": f"Bearer {key}"}


async def _signup_and_key(
    client: httpx.AsyncClient, *, tenant_name: str, email: str, password: str
) -> dict[str, str]:
    signup = await client.post(
        "/admin/auth/signup",
        json={"tenant_name": tenant_name, "email": email, "password": password},
    )
    assert signup.status_code == 201, f"signup failed: {signup.text}"
    token = (
        await client.post("/admin/auth/login", json={"email": email, "password": password})
    ).json()["access_token"]
    created = await client.post(
        "/admin/keys",
        json={"name": f"ci-key-{tenant_name}"},
        headers={"Authorization": f"Bearer {token}"},
    )
    assert created.status_code == 201, f"key creation failed: {created.text}"
    return {"key": created.json()["key"]}


async def _upload(
    client: httpx.AsyncClient,
    key: str,
    *,
    filename: str,
    data: bytes,
    purpose: str,
    content_type: str,
) -> httpx.Response:
    return await client.post(
        "/v1/files",
        files={"file": (filename, data, content_type)},
        data={"purpose": purpose},
        headers=_bearer(key),
    )

# Tiny caps so the realistic "above outer cap / below file cap" window is a few KiB.
_OUTER_JSON_CAP = 1024  # /v1/ + /admin/ JSON body cap
_FILE_CAP = 8192  # per-file cap (Settings.files_max_bytes)


